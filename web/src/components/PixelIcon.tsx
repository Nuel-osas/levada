export type GlyphName = keyof typeof GLYPHS;

function toPath(rows: readonly string[]) {
  let d = "";
  rows.forEach((row, y) => {
    // run-length encode each row so the path stays small
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let w = 1;
      while (row[x + w] === "#") w++;
      d += `M${x} ${y}h${w}v1h-${w}z`;
      x += w;
    }
  });
  return d;
}
const PATHS = Object.fromEntries(Object.entries(GLYPHS).map(([k, rows]) => [k, toPath(rows)])) as Record<GlyphName, string>;

/** `scale` must be a whole number: 1 art pixel = `scale` CSS pixels. */
export function PixelIcon({ name, scale = 2, className }: { name: GlyphName; scale?: number; className?: string }) {
  return (
    <svg
      className={className}
      viewBox="0 0 16 16"
      width={16 * scale}
      height={16 * scale}
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
    >
      <path fill="currentColor" d={PATHS[name]} />
    </svg>
  );
}
