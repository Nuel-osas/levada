KERN = {'LE': -1, 'VA': -2, 'DA': -1}


def word(font, text, track=3, kern=None, col='k'):
    kern = kern or {}
    glyphs = [font[ch] for ch in text]
    h = len(glyphs[0])
    w = sum(len(g[0]) for g in glyphs) + track * (len(glyphs) - 1) + sum(kern.get(text[i:i + 2], 0) for i in range(len(text) - 1))
    cv = Canvas(w, h)
    x = 0
    for i, g in enumerate(glyphs):
        for yy, row in enumerate(g):
            for xx, chh in enumerate(row):
                if chh == '#':
                    cv.set(x + xx, yy, col)
        x += len(g[0]) + track
        if i < len(text) - 1:
            x += kern.get(text[i:i + 2], 0)
    return cv
